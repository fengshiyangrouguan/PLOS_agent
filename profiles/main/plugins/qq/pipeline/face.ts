/**
 * 表情 ID → 展示文本；未知 ID 给出可辨认的兜底。
 *
 * 兜底带上 ID 是刻意的：旧版主消息用 `[未知表情:{id}]`、转发子消息用 `[未知表情]`，
 * 两者不一致导致同一个表情在两处显示不同。这里统一为带 ID 的形态——
 * 至少能让人去查表补全。
 * @param id - OneBot `face` 段的 `id`，或 emoji 字符。
 * @returns 展示文本。
 */
export function faceToText(id: unknown): string {
  const key = String(id)
  return FACE_BY_ID[key] ?? `[未知表情:${key}]`
}

/**
 * 展示文本 → 数字 ID 的反查表。
 *
 * **只收数字键**：emoji 键的值常与数字键重复，收进来会互相覆盖。
 * 重复值取**最先出现**的数字键（`Object.entries` 的插入序），保证结果稳定。
 */
export const FACE_TEXT_TO_ID: Readonly<Record<string, string>> = (() => {
  const table: Record<string, string> = {}
  for (const [id, text] of Object.entries(FACE_BY_ID)) {
    if (!/^\d+$/.test(id)) continue
    if (!(text in table)) table[text] = id
  }
  return table
})()

/**
 * ★★ **回传给模型时列举的常用表情**。
 *
 * 这是**给她看的**（model-facing ✓）—— 认出不出时不该只甩一句"失败" ✗，
 * 那样她只能一次次试 ✓；给她几个能用的名字，她立刻就能改对 ✓。
 *
 * ★ 刻意是**手挑的短名单**：错的时候要"够用且不啰嗦" ✓
 * （把 150 多个名字倒给她是噪声 ✗）。
 */
export const FACE_EXAMPLES = '笑哭、呲牙、偷笑、流泪、害羞、玫瑰、赞、比心、狗头、吃瓜'

/**
 * 出站切分出来的一段：**一段纯文本**或**一个表情**。
 *
 * ★ 刻意是**中立形状**（不认识 OneBot 的 `Segment`）—— `face.ts` 属于渲染层，
 * 不该认识协议类型 ✓；由 adapter 把它翻译成 `face` 段 ✓。
 */
export type OutgoingPart =
  | { readonly kind: 'text', readonly text: string }
  | { readonly kind: 'face', readonly id: string }

/**
 * ★★ **出站反解析**：把展示文本切回"文本 ＋ 表情"。
 *
 * 与 {@link faceToText} **互为逆** —— 那条路让模型看到 `[表情：笑哭]`，
 * 这条路把她写的 `[表情：笑哭]` 还原成可发送的表情 ✓。
 * （`face.ts` 的模块注释里那句"同时被出站还原复用"说的就是它 ✓。）
 *
 * ## 认两种形态
 *
 * | 写法 | 处理 |
 * |:--|:--|
 * | `[表情：笑哭]` | 查 {@link FACE_TEXT_TO_ID} ✓ |
 * | `[未知表情:237]` | ★ **直接用那个 id** —— `faceToText` 的兜底自带 id ✓，说明她**说出了**是哪个表情，只是名字不在表里 ⇒ **比丢掉好得多** ✓ |
 *
 * ## ★ 都不认就**整段丢掉**（用户定案）
 *
 * 发一个表里没有的表情名没有意义 ✓；而**把它当普通文本发出去更糟** ✗
 * —— 对方会收到一串方括号 ✓。
 *
 * @param text - 她写的正文。
 * @returns 切好的段。**相邻文本已合并、空段不产出** ✓。
 */
export function parseOutgoingFaces(text: string): OutgoingPart[] {
  const parts: OutgoingPart[] = []
  // ★ **容忍半角冒号与两侧空格** —— 她的写法不受控 ✓。
  //   实测（2026-10-15）：写成半角 `[表情:笑哭]` 会落进"认不出"那条路 ⇒ 全丢掉 ⇒
  //   若整条消息**只有**那个表情，就变成**空段数组** ⇒ 协议端直接拒：
  //   `message segment array must not be empty` ✗。
  const pattern = /\[(表情|未知表情)\s*[:：]\s*([^\]]*)\]/g
  let cursor = 0

  /**
   * 并入一段纯文本（空串跳过；与上一段文本合并）。
   *
   * @param value - 要并入的文本。
   */
  const pushText = (value: string): void => {
    if (value === '') return
    const last = parts.at(-1)
    if (last !== undefined && last.kind === 'text') {
      parts[parts.length - 1] = { kind: 'text', text: last.text + value }
      return
    }
    parts.push({ kind: 'text', text: value })
  }

  for (const match of text.matchAll(pattern)) {
    const at = match.index ?? 0
    const whole = match[0]
    const tag = match[1]
    const body = match[2] ?? ''
    pushText(text.slice(cursor, at))
    cursor = at + whole.length

    if (tag === '未知表情') {
      if (/^\d+$/.test(body.trim())) parts.push({ kind: 'face', id: body.trim() })
      continue
    }
    const id = FACE_TEXT_TO_ID[`[表情：${body.trim()}]`]
    // ★ 表里没有 ⇒ 这里什么都不产出 ⇒ **整段消失** ✓（前后文本照旧接上 ✓）。
    if (id !== undefined) parts.push({ kind: 'face', id })
  }

  pushText(text.slice(cursor))
  return parts
}

