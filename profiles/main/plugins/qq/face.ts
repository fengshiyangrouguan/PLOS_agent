/**
 * 表情 ID → 展示文本；未知 ID 给出可辨认的兜底。
 *
 * 兜底带上 ID 是刻意的：旧版主消息用 `[未知表情:{id}]`、转发子消息用 `[未知表情]`，
 * 两者不一致导致同一个表情在两处显示不同。这里统一为带 ID 的形态——
 * 至少能让人去查表补全。
 * @param id - OneBot `face` 段的 `id`，或 emoji 字符。
 * @returns 展示文本。
 */
export function faceToText(id: unknown): string {
  const key = String(id)
  return FACE_BY_ID[key] ?? `[未知表情:${key}]`
}

/**
 * 展示文本 → 数字 ID 的反查表。
 *
 * **只收数字键**：emoji 键的值常与数字键重复，收进来会互相覆盖。
 * 重复值取**最先出现**的数字键（`Object.entries` 的插入序），保证结果稳定。
 */
export const FACE_TEXT_TO_ID: Readonly<Record<string, string>> = (() => {
  const table: Record<string, string> = {}
  for (const [id, text] of Object.entries(FACE_BY_ID)) {
    if (!/^\d+$/.test(id)) continue
    if (!(text in table)) table[text] = id
  }
  return table
})()
